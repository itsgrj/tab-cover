"""Builds cover-tokens.js: the Seeghra tokens the cover needs (White and g100 only) plus src/cover.css, for the shadow root."""
import re, json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
tokens = (root / 'ui/tokens.css').read_text()
cover = (root / 'src/cover.css').read_text()
tokens = re.sub(r'/\*.*?\*/', '', tokens, flags=re.S)
# collect blocks: selector -> {var: value}
static, white, g100 = {}, {}, {}
for m in re.finditer(r'([^{}]+)\{([^{}]*)\}', tokens):
    sel = ' '.join(m.group(1).split())
    decls = dict(re.findall(r'(--sg-[\w-]+)\s*:\s*([^;]+);', m.group(2)))
    if not decls: continue
    if 'data-sg-layer' in sel or '@media' in sel: continue
    if sel == ':root':
        static.update(decls)
    elif 'data-sg-theme="white"' in sel:
        white.update(decls)
    elif sel.startswith('[data-sg-theme="g100"]'):
        g100.update(decls)
need = set(re.findall(r'var\((--sg-[\w-]+)', cover))
def resolve(names):
    out, todo = set(), list(names)
    while todo:
        n = todo.pop()
        if n in out: continue
        out.add(n)
        for src in (static, white, g100):
            if n in src: todo += re.findall(r'var\((--sg-[\w-]+)', src[n])
    return out
allv = resolve(need)
missing = [n for n in allv if n not in static and n not in white and n not in g100]
assert not missing, missing
def block(sel, src):
    body = ''.join(f'{k}:{v};' for k, v in sorted(src.items()) if k in allv)
    return f'{sel}{{{body}}}'
css = block(':host', static) + block(':host,[data-sg-theme="white"]', white) + block('[data-sg-theme="g100"]', g100) + '\n' + cover
(root / 'cover-tokens.js').write_text('/* Generated by tools/build.py from ui/tokens.css and src/cover.css. Do not edit. */\nself.TC_COVER_CSS = ' + json.dumps(css) + ';\n')
print(len(allv), 'tokens,', len(css), 'bytes')
